//! Example demonstrating stdgo os package:
//! 1. os.File creation, streaming writes, seeks, and reads
//! 2. os.mkdirAll, os.readDir, os.stat
//! 3. os.getenv, os.lookupEnv with explicit environment map

const std = @import("std");
const stdgo = @import("stdgo");
const os = stdgo.os;

pub fn main(init: std.process.Init) !void {
    const gpa = init.arena.allocator();
    const io = init.io;

    std.debug.print("=== stdgo: os (File, Dir, Env) Example ===\n\n", .{});

    // -------------------------------------------------------------
    // 1. Directory creation and File I/O
    // -------------------------------------------------------------
    std.debug.print("1. Directory creation & os.File streaming:\n", .{});

    const scratch_dir = "example_os_scratch";
    try os.mkdirAll(io, scratch_dir, 0o755);
    defer os.removeAll(io, scratch_dir) catch {};

    const file_path = scratch_dir ++ "/server.conf";

    var f = try os.create(io, file_path);
    defer _ = f.close() catch {};

    _ = try f.writeString("# Server configuration generated by stdgo\n");
    _ = try f.writeString("port = 8080\n");
    _ = try f.writeString("host = 127.0.0.1\n");
    _ = try f.writeString("tls = true\n");
    try f.sync();

    const info = try f.stat();
    std.debug.print("   Created '{s}': size={d} bytes, is_dir={}\n", .{
        info.name,
        info.size,
        info.is_dir,
    });

    // -------------------------------------------------------------
    // 2. Convenience readFile & readDir
    // -------------------------------------------------------------
    std.debug.print("\n2. os.readFile and os.readDir:\n", .{});

    const file_content = try os.readFile(gpa, io, file_path);
    defer gpa.free(file_content);
    std.debug.print("   Read back content ({d} bytes):\n{s}", .{ file_content.len, file_content });

    const entries = try os.readDir(gpa, io, scratch_dir);
    defer {
        for (entries) |e| gpa.free(e.name);
        gpa.free(entries);
    }
    std.debug.print("   Directory entries in '{s}': {d}\n", .{ scratch_dir, entries.len });
    for (entries) |entry| {
        std.debug.print("   -> {s} (is_dir: {})\n", .{ entry.name, entry.is_dir });
    }

    // -------------------------------------------------------------
    // 3. Explicit Environment Lookup (TigerStyle)
    // -------------------------------------------------------------
    std.debug.print("\n3. os.getenv & os.lookupEnv:\n", .{});

    var env_map = std.process.Environ.Map.init(gpa);
    defer env_map.deinit();

    try env_map.put("APP_ENV", "production");
    try env_map.put("LOG_LEVEL", "DEBUG");

    std.debug.print("   APP_ENV:   '{s}'\n", .{os.getenv(&env_map, "APP_ENV")});
    std.debug.print("   LOG_LEVEL: '{s}'\n", .{os.getenv(&env_map, "LOG_LEVEL")});
    std.debug.print("   MISSING:   '{s}' (lookup is null: {})\n", .{
        os.getenv(&env_map, "MISSING_VAR"),
        os.lookupEnv(&env_map, "MISSING_VAR") == null,
    });

    // -------------------------------------------------------------
    // 4. User Account & Group Lookups (os.user)
    // -------------------------------------------------------------
    std.debug.print("\n4. User & Group Lookups (os.user):\n", .{});
    const curr_u = try os.user.current(gpa, .{ .env = init.environ_map, .io = io });
    defer curr_u.deinit();
    std.debug.print("   Current User: username='{s}', uid={s}, gid={s}, home='{s}'\n", .{
        curr_u.username,
        curr_u.uid,
        curr_u.gid,
        curr_u.home_dir,
    });

    // -------------------------------------------------------------
    // 5. Host & Process Metadata (os.getwd, os.getpid, os.hostname)
    // -------------------------------------------------------------
    std.debug.print("\n5. Host, Process & Advanced File Operations:\n", .{});
    const wd = try os.getwd(gpa, io);
    defer gpa.free(wd);
    std.debug.print("   Current Working Directory: '{s}'\n", .{wd});

    const host = try os.hostname(gpa, init.environ_map);
    defer gpa.free(host);
    std.debug.print("   Process PID: {d}, PPID: {d}, Hostname: '{s}', TempDir: '{s}'\n", .{
        os.getpid(),
        os.getppid(),
        host,
        os.tempDir(init.environ_map),
    });

    // Truncate & Symlink demonstration
    const link_path = scratch_dir ++ "/server_link.conf";
    try os.symlink(io, "server.conf", link_path);
    const resolved_target = try os.readlink(gpa, io, link_path);
    defer gpa.free(resolved_target);
    std.debug.print("   Created Symlink '{s}' -> '{s}'\n", .{ link_path, resolved_target });

    std.debug.print("   IsNotExist check on nonexistent: {}\n", .{os.isNotExist(error.FileNotFound)});

    std.debug.print("\nos demo completed successfully!\n", .{});
}
